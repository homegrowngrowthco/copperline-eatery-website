// Regenerates netlify/functions/lib/assets.ts: the brand fonts and logo the
// quote-sheet PDF embeds, base64-inlined so esbuild/zip-it-and-ship-it can
// bundle them with zero runtime filesystem reads or netlify.toml plumbing.
// Sources are the SAME @fontsource files the site itself serves (BaseLayout
// imports them), so the emailed PDF and the on-site print sheet share fonts.
// Run after bumping @fontsource packages or replacing public/logo.jpg:
//   node scripts/embed-fn-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const ASSETS = {
  OSWALD_400: 'node_modules/@fontsource/oswald/files/oswald-latin-400-normal.woff',
  OSWALD_700: 'node_modules/@fontsource/oswald/files/oswald-latin-700-normal.woff',
  MERRIWEATHER_400: 'node_modules/@fontsource/merriweather/files/merriweather-latin-400-normal.woff',
  MERRIWEATHER_700: 'node_modules/@fontsource/merriweather/files/merriweather-latin-700-normal.woff',
  LOGO_JPG: 'public/logo.jpg',
};

let out = `// GENERATED by scripts/embed-fn-assets.mjs — do not edit by hand.
// Brand fonts (same @fontsource files the site serves) + logo for the
// quote-sheet PDF, base64-inlined for bundling. Regenerate with:
//   node scripts/embed-fn-assets.mjs

function decode(b64: string): Uint8Array {
  return new Uint8Array(Buffer.from(b64, 'base64'));
}
`;

for (const [name, path] of Object.entries(ASSETS)) {
  const b64 = readFileSync(path).toString('base64');
  out += `\nexport const ${name} = decode(\n  '${b64}'\n);\n`;
  console.log(`${name}: ${path} (${b64.length} b64 chars)`);
}

writeFileSync('netlify/functions/lib/assets.ts', out);
console.log('wrote netlify/functions/lib/assets.ts');
